// @ts-check
/**
 * Keeps the packaged backend reachable as the `dsh` CLI from any terminal.
 *
 * The NSIS installer (build/installer.nsh) seeds the shims at install time;
 * this module rewrites them on every app launch so they always point at THIS
 * install's resources/backend — upgrades, install-directory changes, and
 * deleted shims all self-heal — and repairs the user-PATH entry if other
 * tooling dropped it (build/cli/install-cli-path.ps1, shared with the
 * installer).
 *
 * Windows-only by design: macOS builds ship the .app bundle and do not seed a
 * `dsh` CLI shim. The shims run the backend under the user's Node from PATH,
 * exactly like the Electron shell itself spawns it (cwd = backend root).
 */
'use strict'

const { spawn } = require('node:child_process')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

/**
 * Mirrors @deepseek-ai/dsh-home-paths: $DSH_HOME overrides the default
 * ~/.dsh home, so a redirected home gets a redirected CLI dir too.
 * @param {NodeJS.ProcessEnv} [env]
 * @returns {string}
 */
function dshHomeDir (env = process.env) {
  return env.DSH_HOME ? path.resolve(env.DSH_HOME) : path.join(os.homedir(), '.dsh')
}

/**
 * The two shims: dsh.cmd serves cmd.exe and PowerShell, the extensionless
 * dsh serves Git Bash. Keep in sync with build/installer.nsh — same template,
 * this copy just has the backend root spliced in.
 * @param {string} backendRoot
 */
function shimContents (backendRoot) {
  const cmd = [
    '@echo off',
    'rem Installed by DeepSeek Harness. Regenerated by the app on every launch.',
    'setlocal',
    `set "DSH_BACKEND=${backendRoot}"`,
    'if not exist "%DSH_BACKEND%\\lib\\bin.js" (',
    '  echo [dsh] backend not found at "%DSH_BACKEND%" 1>&2',
    '  exit /b 1',
    ')',
    'pushd "%DSH_BACKEND%"',
    'node "lib\\bin.js" %*',
    'set "DSH_RC=%ERRORLEVEL%"',
    'popd',
    'exit /b %DSH_RC%',
    '',
  ].join('\r\n')
  // Backslash Windows paths work throughout git-bash (cd, [ -f ], node argv),
  // so the template stays identical to the cmd one.
  const sh = [
    '#!/usr/bin/env bash',
    '# Installed by DeepSeek Harness. Regenerated by the app on every launch.',
    `DSH_BACKEND="${backendRoot}"`,
    'if [ ! -f "$DSH_BACKEND\\lib\\bin.js" ]; then',
    '  echo "[dsh] backend not found at $DSH_BACKEND" >&2',
    '  exit 1',
    'fi',
    'cd "$DSH_BACKEND" || exit 1',
    'exec node "$DSH_BACKEND\\lib\\bin.js" "$@"',
    '',
  ].join('\n')
  return { 'dsh.cmd': cmd, dsh: sh }
}

/**
 * Rewrite the shims (only when content changes) and repair the user PATH
 * entry. Failures propagate to the caller, which treats this as best-effort.
 * @param {string} backendRoot
 * @returns {Promise<void>}
 */
async function ensureCliShim (backendRoot) {
  const binDir = path.join(dshHomeDir(), 'bin')
  fs.mkdirSync(binDir, { recursive: true })
  for (const [name, content] of Object.entries(shimContents(backendRoot))) {
    const file = path.join(binDir, name)
    let current = null
    try {
      current = fs.readFileSync(file, 'utf8')
    } catch {
      current = null // absent or unreadable: (re)write it
    }
    if (current !== content) fs.writeFileSync(file, content)
  }
  const helper = path.join(process.resourcesPath, 'cli', 'install-cli-path.ps1')
  if (!fs.existsSync(helper)) throw new Error(`PATH helper missing: ${helper}`)
  await new Promise((resolve, reject) => {
    const child = spawn('powershell.exe',
      ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', helper],
      {
        stdio: 'ignore',
        windowsHide: true,
        env: { ...process.env, DSH_BIN_DIR: binDir },
      })
    child.once('exit', (code) => (code === 0 ? resolve() : reject(new Error(`install-cli-path.ps1 exited ${code}`))))
    child.once('error', reject)
  })
}

module.exports = { dshHomeDir, shimContents, ensureCliShim }
